#!/usr/bin/env node
// Start SENTINEL automatically when you log in to this computer.
//   npm run autostart:install     npm run autostart:remove
//   node scripts/autostart.mjs install --dry-run [--platform=win32|darwin|linux]
// Windows: Task Scheduler (at logon, hidden window) · macOS: launchd LaunchAgent · Linux: systemd --user
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, rmSync, writeFileSync } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const action = process.argv[2];
const dryRun = process.argv.includes('--dry-run');
const platform = process.argv.find((a) => a.startsWith('--platform='))?.split('=')[1] ?? process.platform;
const NODE = process.execPath;
const ENTRY = path.join(ROOT, 'server', 'dist', 'index.js');
const LOG = path.join(ROOT, 'data', 'sentinel.log');
const NAME = 'SENTINEL';

function write(file, content) {
  if (dryRun) {
    console.log(`--- ${file}\n${content}`);
    return;
  }
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log(`wrote ${file}`);
}

function run(cmd, args) {
  if (dryRun) {
    console.log(`$ ${cmd} ${args.join(' ')}`);
    return;
  }
  execFileSync(cmd, args, { stdio: 'inherit' });
}

const vbsQuote = (s) => s.replace(/"/g, '""');

const targets = {
  win32: {
    install() {
      // A tiny VBScript launches node with a hidden window and appends output to data/sentinel.log.
      const vbs = path.join(ROOT, 'bin', 'sentinel-autostart.vbs');
      const cmdline = `cmd /c ""${vbsQuote(NODE)}"" ""${vbsQuote(ENTRY)}"" >> ""${vbsQuote(LOG)}"" 2>&1`;
      write(vbs, `' Generated by SENTINEL (scripts/autostart.mjs)\r\nCreateObject("WScript.Shell").Run "${cmdline}", 0, False\r\n`);
      run('schtasks', ['/Create', '/F', '/TN', NAME, '/SC', 'ONLOGON', '/RL', 'LIMITED', '/TR', `wscript.exe "${vbs}"`]);
    },
    remove() {
      run('schtasks', ['/Delete', '/F', '/TN', NAME]);
      rmSync(path.join(ROOT, 'bin', 'sentinel-autostart.vbs'), { force: true });
    },
  },
  darwin: {
    plist: path.join(os.homedir(), 'Library', 'LaunchAgents', 'com.sentinel.dashboard.plist'),
    install() {
      const xml = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;');
      write(
        this.plist,
        `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key><string>com.sentinel.dashboard</string>
  <key>ProgramArguments</key>
  <array><string>${xml(NODE)}</string><string>${xml(ENTRY)}</string></array>
  <key>WorkingDirectory</key><string>${xml(ROOT)}</string>
  <key>RunAtLoad</key><true/>
  <key>KeepAlive</key><true/>
  <key>StandardOutPath</key><string>${xml(LOG)}</string>
  <key>StandardErrorPath</key><string>${xml(LOG)}</string>
</dict>
</plist>
`,
      );
      run('launchctl', ['unload', this.plist]);
      run('launchctl', ['load', '-w', this.plist]);
    },
    remove() {
      if (existsSync(this.plist) || dryRun) run('launchctl', ['unload', '-w', this.plist]);
      if (!dryRun) rmSync(this.plist, { force: true });
    },
  },
  linux: {
    unit: path.join(os.homedir(), '.config', 'systemd', 'user', 'sentinel.service'),
    install() {
      write(
        this.unit,
        `[Unit]
Description=SENTINEL Security Command Center (go2rtc + dashboard)
After=network-online.target

[Service]
ExecStart="${NODE}" "${ENTRY}"
WorkingDirectory=${ROOT}
Restart=on-failure
RestartSec=5
NoNewPrivileges=true

[Install]
WantedBy=default.target
`,
      );
      run('systemctl', ['--user', 'daemon-reload']);
      run('systemctl', ['--user', 'enable', '--now', 'sentinel.service']);
      console.log('Tip: to start even before you log in, run once: sudo loginctl enable-linger $USER');
    },
    remove() {
      run('systemctl', ['--user', 'disable', '--now', 'sentinel.service']);
      if (!dryRun) rmSync(this.unit, { force: true });
      run('systemctl', ['--user', 'daemon-reload']);
    },
  },
};

const t = targets[platform];
if (!t || !['install', 'remove'].includes(action)) {
  console.error('usage: node scripts/autostart.mjs install|remove [--dry-run] (Windows, macOS, Linux)');
  process.exit(2);
}
if (action === 'install' && !existsSync(ENTRY) && !dryRun) {
  console.error('Build first: npm run build');
  process.exit(2);
}
try {
  t[action]();
  if (!dryRun) console.log(action === 'install' ? `✔ SENTINEL will start automatically at login. Logs: ${LOG}` : '✔ Autostart removed.');
} catch (err) {
  console.error(`✖ ${err.message}`);
  process.exit(1);
}
